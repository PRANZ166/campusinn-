/**
 * Campus Inn+ — Frontend Build Script for Vercel & Production
 * Reads environment variables from Vercel (e.g. BACKEND_URL, CAMPUS_INN_API_URL)
 * and generates runtime config + rewrites.
 */
const fs = require('fs');
const path = require('path');

const rawBackendUrl =
  process.env.CAMPUS_INN_API_URL ||
  process.env.BACKEND_URL ||
  process.env.API_URL ||
  process.env.NEXT_PUBLIC_API_URL ||
  '';

if (rawBackendUrl) {
  const backendBase = rawBackendUrl.replace(/\/+$/, '').replace(/\/api\/v1$/, '');
  const apiUrl = `${backendBase}/api/v1`;

  console.log(`[Vercel Build] Configuring Backend URL: ${backendBase}`);

  // 1. Write runtime config file for browser
  const configJsPath = path.resolve(__dirname, 'js', 'config.js');
  fs.writeFileSync(
    configJsPath,
    `// Auto-generated by Vercel build step\nwindow.CAMPUS_INN_API_URL = ${JSON.stringify(apiUrl)};\n`,
    'utf8'
  );
  console.log(`[Vercel Build] Created js/config.js pointing to ${apiUrl}`);

  // 2. Update vercel.json with reverse-proxy rewrites
  const vercelJsonPath = path.resolve(__dirname, 'vercel.json');
  const vercelConfig = {
    cleanUrls: true,
    trailingSlash: false,
    rewrites: [
      {
        source: '/api/:match*',
        destination: `${backendBase}/api/:match*`
      }
    ]
  };
  fs.writeFileSync(vercelJsonPath, JSON.stringify(vercelConfig, null, 2), 'utf8');
  console.log(`[Vercel Build] Updated vercel.json rewrites pointing to ${backendBase}/api/:match*`);

  // 3. Inject into js/api.js
  const apiJsPath = path.resolve(__dirname, 'js', 'api.js');
  if (fs.existsSync(apiJsPath)) {
    let apiJsContent = fs.readFileSync(apiJsPath, 'utf8');
    apiJsContent = apiJsContent.replace(
      /const INJECTED_API_URL = '.*?';/,
      `const INJECTED_API_URL = ${JSON.stringify(apiUrl)};`
    );
    fs.writeFileSync(apiJsPath, apiJsContent, 'utf8');
    console.log(`[Vercel Build] Injected INJECTED_API_URL into js/api.js`);
  }
} else {
  console.log('[Vercel Build] No BACKEND_URL or CAMPUS_INN_API_URL env var set. Using default relative /api/v1 routing.');
}
